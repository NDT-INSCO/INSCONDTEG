import { _ as doc, a as getDocFromServer } from "./index.esm-T7XjjJ2p.js";
import { o as db } from "./config-BaEX8mXf.js";
//#region src/client/rulesProbe.ts
/**
* A read-only probe for one deployment fact: *do the rules published on the
* Firebase project know the groups path at all?*
*
* Why a probe and not an assumption: `firestore.rules` lives in this repository
* and is published to the project by hand (see
* `documentation/FIREBASE_RULES_DEPLOY_AR.md`), so a build can be live while the
* server has never heard of `community_groups`. A member then sees a refusal that
* looks like a bug in the page.
*
* The probe reads a single, deliberately non-existent document under
* `community_groups/<valid-id>`:
*
*   `allow get: if isValidId(groupId)`  → allowed by the published rules too
*
* - read succeeds (document not found)  → the published rules know this path;
* - `permission-denied`                 → they do not: nothing was published yet;
* - `unavailable` / timeout             → the network, not the rules.
*
* It proves **read** permission on the collection, not write permission for every
* policy — the interface says exactly that, so the check is never read as more
* than it is. Nothing is written, ever.
*/
/**
* A document id the rules accept (`^[a-zA-Z0-9_-]+$`, ≤128) and no group can own:
* group ids are generated by Firestore, which never starts with `rules-probe-`.
*/
function probeId(now) {
	return `rules-probe-${now}`;
}
async function probeGroupRules(now = Date.now()) {
	if (!db) return {
		state: "unknown",
		code: null,
		checkedAt: null
	};
	try {
		await getDocFromServer(doc(db, "community_groups", probeId(now)));
		return {
			state: "ready",
			code: null,
			checkedAt: now
		};
	} catch (error) {
		const rawCode = error?.code;
		const code = typeof rawCode === "string" ? rawCode : null;
		if (code === "permission-denied") return {
			state: "missing",
			code,
			checkedAt: now
		};
		if (code === "unavailable" || code === "deadline-exceeded") return {
			state: "offline",
			code,
			checkedAt: now
		};
		return {
			state: "unknown",
			code,
			checkedAt: now
		};
	}
}
//#endregion
export { probeGroupRules, probeId };
