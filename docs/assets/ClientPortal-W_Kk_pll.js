function formatDownloadTimestamp(iso, language) {
	const parsed = new Date(iso);
	if (Number.isNaN(parsed.getTime())) return iso;
	try {
		return parsed.toLocaleTimeString(language === "ar" ? "ar-EG" : "en-GB", {
			hour: "2-digit",
			minute: "2-digit"
		});
	} catch {
		return iso.slice(11, 16);
	}
}
