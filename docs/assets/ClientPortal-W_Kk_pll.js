function isValidEntry(value, companyId) {
	if (!value || typeof value !== "object") return false;
	const candidate = value;
	return typeof candidate.reportId === "string" && candidate.reportId.length > 0 && typeof candidate.companyId === "string" && candidate.companyId === companyId && typeof candidate.reportNumber === "string" && candidate.reportNumber.length > 0 && typeof candidate.method === "string" && typeof candidate.downloadedAt === "string";
}
/**
* Loads up to the last 5 downloaded inspection reports for a specific company dossier.
*/
function loadRecentDownloadedReports(companyId) {
	if (!companyId || typeof localStorage === "undefined") return [];
	try {
		const raw = localStorage.getItem(getStorageKey(companyId));
		if (!raw) return [];
		const parsed = JSON.parse(raw);
		if (!Array.isArray(parsed)) return [];
		return parsed.filter((item) => isValidEntry(item, companyId)).slice(0, 5);
	} catch {
		return [];
	}
}
/**
* Prepends a downloaded report to the company's recent downloads list (deduplicated, max 5)
* and persists it to localStorage.
*/
function recordRecentDownloadedReport(companyId, report, downloadedAtIso = (/* @__PURE__ */ new Date()).toISOString()) {
	if (!companyId || report.companyId && report.companyId !== companyId) return loadRecentDownloadedReports(companyId);
	const updated = [{
		reportId: report.id,
		companyId,
		reportNumber: report.reportNumber,
		method: report.method,
		componentOrJointId: report.componentOrJointId,
		inspectionDate: report.inspectionDate,
		inspectorName: report.inspectorName,
		downloadedAt: downloadedAtIso,
		reportSnapshot: {
			...report,
			companyId
		}
	}, ...loadRecentDownloadedReports(companyId).filter((item) => item.reportId !== report.id)].slice(0, 5);
	try {
		if (typeof localStorage !== "undefined") localStorage.setItem(getStorageKey(companyId), JSON.stringify(updated));
	} catch {}
	return updated;
}
/**
* Clears all recent download entries for the specified company dossier.
*/
function clearRecentDownloadedReports(companyId) {
	if (!companyId) return [];
	try {
		if (typeof localStorage !== "undefined") localStorage.removeItem(getStorageKey(companyId));
	} catch {}
	return [];
}
/**
* Resolves the freshest CompanyInspectionReport record from live company reports,
* falling back to the stored snapshot if the report is outside the active filter.
*/
function resolveRecentReportForDownload(entry, companyReports) {
	const liveMatch = companyReports.find((r) => r.id === entry.reportId && (!r.companyId || r.companyId === entry.companyId));
	if (liveMatch) return liveMatch;
	if (entry.reportSnapshot && (!entry.reportSnapshot.companyId || entry.reportSnapshot.companyId === entry.companyId)) return entry.reportSnapshot;
	return null;
}
